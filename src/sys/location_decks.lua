local Decks = {}
Decks.__index = Decks

local Recipe = require("src.sys.location_deck_recipe")
local whole = Recipe.whole

-- Validate every recipe before consuming randomness or publishing mission state.
function Decks.new(assignments, locations, pool, random)
    local cells = {}
    for cell in pairs(assignments) do cells[#cells + 1] = cell end
    table.sort(cells)
    for _, cell in ipairs(cells) do
        local id = assignments[cell]
        local location = locations.byId[id]
        assert(location, "Unknown location: " .. tostring(id))
        assert(whole(location.deck_size), id .. ": deck_size must be a nonnegative integer")
        local recipe = location.deck_build
        local total = Recipe.validate(recipe, id)
        for _, entry in ipairs(recipe) do
            assert(entry.qty == 0 or not require("src.sys.location_card_traits").hunt({ card_type = entry.type }),
                id .. ": hunt cards cannot be generated by ordinary deck recipes")
            assert(entry.qty == 0 or (pool.byType[entry.type] and #pool.byType[entry.type] > 0),
                id .. ": no eligible cards for type " .. entry.type)
            if entry.qty > 0 then
                for _, cardId in ipairs(pool.byType[entry.type]) do
                    local definition = assert(pool.byId[cardId], "Unknown location card " .. cardId)
                    require("src.sys.location_card_state").initialize({}, definition)
                    require("src.sys.talent_tests").resolve(definition)
                end
            end
        end
        assert(total == location.deck_size, id .. ": deck_build quantities must total deck_size")
    end
    local function pick(limit)
        return random and random:random(limit) or love.math.random(limit)
    end
    local self = setmetatable({ byCell = {}, pool = pool }, Decks)
    local serial = 0
    for _, cell in ipairs(cells) do
        local id = assignments[cell]
        local state = { locationId = id, locationName = locations.byId[id].name or id,
            drawPile = {}, discardPile = {}, inPlay = {}, inPlayOrder = {}, types = {}, revision = 0 }
        for _, entry in ipairs(locations.byId[id].deck_build) do
            state.types[entry.type] = true
            local candidates = pool.byType[entry.type]
            for _ = 1, entry.qty do
                serial = serial + 1
                local instance = {
                    instanceId = "location_card_" .. serial,
                    cardId = candidates[pick(#candidates)],
                }
                require("src.sys.location_card_state").initialize(instance, pool.byId[instance.cardId])
                state.drawPile[#state.drawPile + 1] = instance
            end
        end
        for i = #state.drawPile, 2, -1 do
            local j = pick(i)
            state.drawPile[i], state.drawPile[j] = state.drawPile[j], state.drawPile[i]
        end
        self.byCell[cell] = state
    end
    return self
end

local function copy(source)
    local result = {}
    for key, value in pairs(source) do result[key] = value end
    return result
end

-- Queries derive counts from the actual draw pile; zero-count recipe types remain visible.
function Decks:summary(cell)
    local state = assert(self.byCell[cell], "Unknown location cell: " .. tostring(cell))
    local counts, types = {}, {}
    local traits = require("src.sys.location_card_traits")
    for kind in pairs(state.types) do if not traits.hunt({ card_type = kind }) then counts[kind] = 0 end end
    for _, card in ipairs(state.drawPile) do
        local kind = self.pool.byId[card.cardId].card_type
        if not traits.hunt(self.pool.byId[card.cardId]) then counts[kind] = (counts[kind] or 0) + 1 end
    end
    for kind in pairs(counts) do types[#types + 1] = kind end
    table.sort(types)
    return { total = #state.drawPile, byType = counts, types = types, revealed = #state.inPlayOrder }
end

-- Hidden-role counts cannot be reconstructed by subtracting ordinary counts from totals.
-- The eligibility flag is public board configuration, never based on a card's actual position.
function Decks:publicSummary(cell)
    local result = self:summary(cell)
    if self.huntCells and self.huntCells[cell] then
        result.total, result.concealed = 0, true
        for _, count in pairs(result.byType) do result.total = result.total + count end
    end
    return result
end

function Decks:publicMillCounts(cell, staged)
    if not (self.huntCells and self.huntCells[cell]) then return staged.before, staged.after, false end
    local remaining = 0
    for _, card in ipairs(staged.drawPile) do
        if not require("src.sys.location_card_traits").hunt(self.pool.byId[card.cardId]) then remaining = remaining + 1 end
    end
    return self:publicSummary(cell).total, remaining, true
end

-- Detached preparation lets callers validate all costs before publishing a draw.
function Decks:prepareDraw(cell)
    local state = assert(self.byCell[cell], "Unknown location cell: " .. tostring(cell))
    if #state.drawPile == 0 then return nil end
    local staged = { source = state, revision = state.revision, drawPile = copy(state.drawPile),
        inPlay = copy(state.inPlay), inPlayOrder = copy(state.inPlayOrder) }
    staged.card = table.remove(staged.drawPile)
    if staged.card.faceUp then staged.card = copy(staged.card); staged.card.faceUp = nil end
    staged.inPlay[staged.card.instanceId] = staged.card
    staged.inPlayOrder[#staged.inPlayOrder + 1] = staged.card.instanceId
    return staged
end

function Decks:commitDraw(cell, staged)
    local state = self.byCell[cell]
    if not staged or staged.source ~= state or staged.revision ~= state.revision then return false end
    state.revealedTopId = nil
    state.drawPile, state.inPlay, state.inPlayOrder = staged.drawPile, staged.inPlay, staged.inPlayOrder
    state.revision = state.revision + 1
    if self.onChanged then self.onChanged(cell) end
    return true
end

-- The end of the array is the top of the deck. Empty decks do not reshuffle.
function Decks:draw(cell)
    local staged = self:prepareDraw(cell)
    if staged and self:commitDraw(cell, staged) then return staged.card end
end

-- Ordinary milling discards. Hunt and sabotage cards enter play, in mill order.
function Decks:prepareMill(cell, count)
    assert(whole(count), "Milling count must be a nonnegative integer")
    local state = assert(self.byCell[cell], "Missing milling location")
    local staged = { source = state, revision = state.revision, drawPile = copy(state.drawPile),
        discardPile = copy(state.discardPile), cards = {}, requested = count, before = #state.drawPile,
        locationId = state.locationId, locationName = state.locationName, cell = cell,
        inPlay = copy(state.inPlay), inPlayOrder = copy(state.inPlayOrder), entered = {} }
    for _ = 1, math.min(count, #state.drawPile) do
        local card = table.remove(staged.drawPile)
        if card.faceUp then card = copy(card); card.faceUp = nil end
        local definition = assert(self.pool.byId[card.cardId], "Unknown milled card")
        local enters = require("src.sys.location_card_traits").entersOnMill(definition)
        if enters then
            card = copy(card) -- Engagement preparation must never mutate the live draw pile.
            staged.inPlay[card.instanceId] = card
            staged.inPlayOrder[#staged.inPlayOrder + 1] = card.instanceId
            staged.entered[#staged.entered + 1] = card
        else staged.discardPile[#staged.discardPile + 1] = card end
        staged.cards[#staged.cards + 1] = { instanceId = card.instanceId, cardId = card.cardId,
            name = definition.name or card.cardId, destination = enters and "inPlay" or "discardPile" }
    end
    staged.actual, staged.after = #staged.cards, #staged.drawPile
    return staged
end
function Decks:canCommitMill(cell, staged)
    local state = self.byCell[cell]
    return staged and not staged.committed and staged.source == state and state.revision == staged.revision
end
function Decks:commitMill(cell, staged)
    if not self:canCommitMill(cell, staged) then return false end
    local state = self.byCell[cell]
    if staged.actual > 0 then state.revealedTopId = nil end
    state.drawPile, state.discardPile = staged.drawPile, staged.discardPile
    state.inPlay, state.inPlayOrder = staged.inPlay, staged.inPlayOrder
    state.revision, staged.committed = state.revision + 1, true
    if self.onChanged then self.onChanged(cell) end
    return true
end

function Decks:discard(cell, instanceId)
    local state = assert(self.byCell[cell], "Unknown location cell: " .. tostring(cell))
    local card = state.inPlay[instanceId]
    if not card then return false end
    require("src.sys.location_engagement").clear(card)
    state.inPlay[instanceId] = nil
    for i, id in ipairs(state.inPlayOrder) do
        if id == instanceId then table.remove(state.inPlayOrder, i); break end
    end
    state.revision = state.revision + 1
    state.discardPile[#state.discardPile + 1] = card
    if self.onChanged then self.onChanged(cell) end
    return true
end

-- A face-up top card is information, not an in-play encounter.
function Decks:revealedTop(cell)
    local deck = self.byCell[cell]
    local top = deck and deck.drawPile[#deck.drawPile]
    if top and (top.faceUp or top.instanceId == deck.revealedTopId) then return top end
end
function Decks:prepareScan(excludedCell)
    local plan = { owner = self, cells = {}, results = {} }
    for cell, deck in pairs(self.byCell) do
        if cell ~= excludedCell then
            plan.cells[#plan.cells + 1] = { cell = cell, source = deck, revision = deck.revision,
                drawPile = copy(deck.drawPile) }
        end
    end
    table.sort(plan.cells, function(a, b) return a.cell < b.cell end)
    return plan
end
function Decks:commitScan(plan, random)
    if not plan or plan.owner ~= self or plan.committed then return false end
    for _, entry in ipairs(plan.cells) do
        if self.byCell[entry.cell] ~= entry.source or entry.source.revision ~= entry.revision then return false end
    end
    -- Prepare every permutation before publishing any deck.
    for _, entry in ipairs(plan.cells) do
        local top = entry.drawPile[#entry.drawPile]
        local revealed = top and require("src.sys.location_card_traits").hunt(self.pool.byId[top.cardId])
        if top and not revealed then
            for i = #entry.drawPile, 2, -1 do
                local j = random and random:random(i) or love.math.random(i)
                entry.drawPile[i], entry.drawPile[j] = entry.drawPile[j], entry.drawPile[i]
            end
        end
        if not revealed then
            for i, card in ipairs(entry.drawPile) do
                if card.faceUp then entry.drawPile[i] = copy(card); entry.drawPile[i].faceUp = nil end
            end
        end
        entry.revealedTopId = revealed and top.instanceId or nil
        plan.results[#plan.results + 1] = { cell = entry.cell, card = revealed and copy(top) or nil,
            shuffled = top ~= nil and not revealed, empty = top == nil }
    end
    for _, entry in ipairs(plan.cells) do
        entry.source.drawPile, entry.source.revealedTopId = entry.drawPile, entry.revealedTopId
        entry.source.revision = entry.source.revision + 1
    end
    plan.committed = true
    return true
end
function Decks:faceUpCards(cell)
    local deck, cards = self.byCell[cell], {}
    for i = #deck.drawPile, 1, -1 do
        local card = deck.drawPile[i]
        if card.faceUp or card.instanceId == deck.revealedTopId then cards[#cards+1] = card end
    end
    return cards
end
function Decks:charm(cell,count,session)
    local deck = self.byCell[cell]
    local revealed,entered = 0,0
    for i = #deck.drawPile, math.max(1,#deck.drawPile-count+1), -1 do
        local card = deck.drawPile[i]
        if card.faceUp or card.instanceId == deck.revealedTopId then
            table.remove(deck.drawPile,i)
            card.faceUp = nil
            if require("src.sys.location_card_traits").enemy(self.pool.byId[card.cardId]) then
                card.exhausted,card.engagedAgentId = true,nil
            end
            deck.inPlay[card.instanceId] = card
            deck.inPlayOrder[#deck.inPlayOrder+1] = card.instanceId
            require("src.sys.location_card_entry").committed(session,cell,card)
            entered = entered + 1
        else card.faceUp = true; revealed = revealed + 1 end
    end
    deck.revealedTopId = nil
    deck.revision = deck.revision + 1
    if self.onChanged then self.onChanged(cell) end
    return revealed,entered
end
return Decks
